'use client';

import { useState } from 'react';
import toast from 'react-hot-toast';
import { formatINR } from '@/lib/demo-data';

interface Participant { name: string; email: string; amount: number; percentage: number; }

export default function SplitPage() {
  const [totalAmount, setTotalAmount] = useState(50000);
  const [splitMode, setSplitMode] = useState<'equal' | 'custom' | 'percentage'>('equal');
  const [participants, setParticipants] = useState<Participant[]>([
    { name: 'Arjun Mehta', email: 'arjun@company.com', amount: 0, percentage: 0 },
    { name: 'Priya Sharma', email: 'priya@company.com', amount: 0, percentage: 0 },
    { name: 'Rahul Patel', email: 'rahul@company.com', amount: 0, percentage: 0 },
  ]);

  const computed = participants.map(p => {
    if (splitMode === 'equal') return { ...p, amount: totalAmount / participants.length, percentage: 100 / participants.length };
    if (splitMode === 'percentage') return { ...p, amount: (p.percentage / 100) * totalAmount };
    return p;
  });

  const addParticipant = () => setParticipants([...participants, { name: '', email: '', amount: 0, percentage: 0 }]);
  const removeParticipant = (i: number) => setParticipants(participants.filter((_, idx) => idx !== i));

  const updateParticipant = (i: number, field: keyof Participant, value: string | number) => {
    const updated = [...participants];
    (updated[i] as unknown as Record<string, string | number>)[field] = value;
    setParticipants(updated);
  };

  const copyShareable = () => {
    const text = `Expense Split - ${formatINR(totalAmount)}\n\n${computed.map(p => `${p.name}: ${formatINR(p.amount)}`).join('\n')}\n\nGenerated by InvoiceIQ`;
    navigator.clipboard.writeText(text);
    toast.success('Summary copied to clipboard');
  };

  return (
    <div className="p-8">
      <header className="mb-8">
        <h1 className="text-xl font-bold tracking-tighter text-white">Expense Splitting</h1>
        <p className="text-zinc-500 text-sm mt-1">Split invoices among team members</p>
      </header>

      <div className="grid grid-cols-12 gap-6">
        <div className="col-span-12 lg:col-span-7 space-y-6">
          {/* Amount & Mode */}
          <div className="bg-[#121212] border border-[#262626] rounded-xl p-6 space-y-6">
            <div>
              <label className="text-[10px] text-zinc-500 uppercase tracking-widest font-bold block mb-2">Total Amount</label>
              <input type="number" value={totalAmount} onChange={e => setTotalAmount(Number(e.target.value))} className="w-full bg-black border border-zinc-800 rounded-lg px-4 py-3 text-white text-2xl font-bold focus:border-white focus:outline-none" />
            </div>
            <div>
              <label className="text-[10px] text-zinc-500 uppercase tracking-widest font-bold block mb-2">Split Mode</label>
              <div className="flex gap-2">
                {(['equal', 'custom', 'percentage'] as const).map(mode => (
                  <button key={mode} onClick={() => setSplitMode(mode)} className={`flex-1 py-2.5 rounded-lg text-[12px] font-bold capitalize transition-all ${splitMode === mode ? 'bg-white text-black' : 'border border-zinc-800 text-zinc-400 hover:border-white'}`}>{mode}</button>
                ))}
              </div>
            </div>
          </div>

          {/* Participants */}
          <div className="bg-[#121212] border border-[#262626] rounded-xl p-6">
            <div className="flex items-center justify-between mb-4">
              <h3 className="text-white font-bold">Participants</h3>
              <button onClick={addParticipant} className="text-[11px] font-bold text-white flex items-center gap-1 hover:underline">
                <span className="material-symbols-outlined text-[16px]">add</span>Add Person
              </button>
            </div>
            <div className="space-y-3">
              {participants.map((p, i) => (
                <div key={i} className="flex items-center gap-3 p-3 border border-zinc-800 rounded-lg">
                  <div className="w-8 h-8 rounded-full bg-zinc-800 flex items-center justify-center text-[10px] font-bold text-white">
                    {p.name ? p.name.split(' ').map(w => w[0]).join('') : '?'}
                  </div>
                  <input value={p.name} onChange={e => updateParticipant(i, 'name', e.target.value)} placeholder="Name" className="flex-1 bg-transparent text-white text-sm focus:outline-none" />
                  <input value={p.email} onChange={e => updateParticipant(i, 'email', e.target.value)} placeholder="Email" className="flex-1 bg-transparent text-zinc-400 text-sm focus:outline-none" />
                  {splitMode === 'custom' && (
                    <input type="number" value={p.amount || ''} onChange={e => updateParticipant(i, 'amount', Number(e.target.value))} placeholder="Amount" className="w-28 bg-black border border-zinc-800 rounded px-2 py-1 text-white text-sm text-right focus:outline-none focus:border-white" />
                  )}
                  {splitMode === 'percentage' && (
                    <div className="flex items-center gap-1">
                      <input type="number" value={p.percentage || ''} onChange={e => updateParticipant(i, 'percentage', Number(e.target.value))} placeholder="%" className="w-16 bg-black border border-zinc-800 rounded px-2 py-1 text-white text-sm text-right focus:outline-none focus:border-white" />
                      <span className="text-zinc-500 text-sm">%</span>
                    </div>
                  )}
                  <button onClick={() => removeParticipant(i)} className="text-zinc-600 hover:text-white transition-colors">
                    <span className="material-symbols-outlined text-[18px]">close</span>
                  </button>
                </div>
              ))}
            </div>
          </div>
        </div>

        {/* Settlement */}
        <div className="col-span-12 lg:col-span-5">
          <div className="bg-[#121212] border border-[#262626] rounded-xl p-6 sticky top-8">
            <h3 className="text-white font-bold text-lg mb-6">Settlement Summary</h3>
            <div className="space-y-4 mb-6">
              {computed.map((p, i) => (
                <div key={i} className="flex items-center justify-between p-3 border border-zinc-800 rounded-lg">
                  <div className="flex items-center gap-3">
                    <div className="w-8 h-8 rounded-full bg-white text-black flex items-center justify-center text-[10px] font-bold">
                      {p.name ? p.name.split(' ').map(w => w[0]).join('') : '?'}
                    </div>
                    <div>
                      <p className="text-white text-sm font-medium">{p.name || 'Unnamed'}</p>
                      <p className="text-zinc-500 text-[11px]">{p.email}</p>
                    </div>
                  </div>
                  <span className="text-white font-bold">{formatINR(p.amount)}</span>
                </div>
              ))}
            </div>
            <div className="border-t border-zinc-800 pt-4 mb-6">
              <div className="flex justify-between mb-2">
                <span className="text-zinc-400 text-sm">Total</span>
                <span className="text-white font-bold">{formatINR(totalAmount)}</span>
              </div>
              <div className="flex justify-between">
                <span className="text-zinc-400 text-sm">Per person (avg)</span>
                <span className="text-zinc-400">{formatINR(totalAmount / (participants.length || 1))}</span>
              </div>
            </div>
            <button onClick={copyShareable} className="w-full bg-white text-black py-3 rounded-lg font-bold text-sm hover:bg-zinc-200 transition-colors active:scale-[0.99]">
              Copy Shareable Summary
            </button>
          </div>
        </div>
      </div>
    </div>
  );
}
